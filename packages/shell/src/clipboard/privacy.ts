/**
 * What clipboard history never keeps (docs/betterments.html, "Clipboard
 * history and snippets", the privacy rules), as pure decisions over what
 * the compositor reported and what the shell found out about the copy:
 *
 * - a copy flagged secret by its own types: KDE's password-manager hint
 *   (`x-kde-passwordManagerHint: secret`, which KeePassXC sets), and the
 *   concealed and transient types password managers set for the Mac's
 *   pasteboard convention (nspasteboard.org), which some set here too;
 * - a copy made in a password manager, by app: Dashi's Passwords (the vault)
 *   and a list the person can edit in Settings › Keyboard;
 * - a copy made while a password field had the focus (AT-SPI's role
 *   `password text`);
 * - anything while the screen is shared or recorded, or locked.
 *
 * What is kept is chosen by type: an image, files, or text.
 */

/** The hint KDE's Klipper reads; its value is "secret" for a password. */
export const PASSWORD_MANAGER_HINT = "x-kde-passwordManagerHint";

/** Types that mark a copy as not for history by being there at all. */
const CONCEALED = new Set([
  "org.nspasteboard.concealedtype",
  "org.nspasteboard.transienttype",
  "org.nspasteboard.autogeneratedtype",
  "application/x-nspasteboard-concealed-type",
  "x-kde-passwordmanagerhint-secret",
]);

/** Password managers left out by default (KeePassXC, Bitwarden, 1Password, Seahorse), as app ids or programs. */
export const DEFAULT_LEFT_OUT: readonly string[] = [
  "org.keepassxc.KeePassXC",
  "keepassxc",
  "Bitwarden",
  "bitwarden",
  "com.bitwarden.desktop",
  "1Password",
  "1password",
  "org.gnome.seahorse.Application",
  "seahorse",
];

/** What a left-out entry is called in Settings. */
export const LEFT_OUT_NAMES: Readonly<Record<string, string>> = {
  "org.keepassxc.KeePassXC": "KeePassXC",
  keepassxc: "KeePassXC",
  Bitwarden: "Bitwarden",
  bitwarden: "Bitwarden",
  "com.bitwarden.desktop": "Bitwarden",
  "1Password": "1Password",
  "1password": "1Password",
  "org.gnome.seahorse.Application": "Passwords and Keys",
  seahorse: "Passwords and Keys",
};

/** The left-out list as Settings shows it: one name per app. */
export function leftOutNames(list: readonly string[]): string[] {
  return [...new Set(list.map((id) => LEFT_OUT_NAMES[id] ?? id))];
}

/** Whether a copy's types alone say it is secret (the hint's value is read separately: `hintIsSecret`). */
export function concealedByType(mimeTypes: readonly string[]): boolean {
  return mimeTypes.some((type) => CONCEALED.has(type.toLowerCase()));
}

/** Whether the copy carries KDE's hint, which must be read to know. */
export const hasPasswordHint = (mimeTypes: readonly string[]): boolean => mimeTypes.includes(PASSWORD_MANAGER_HINT);

/** The hint's value read: "secret" (any case, with or without a line end) is a secret; so is a hint that could not be read. */
export function hintIsSecret(value: string | null): boolean {
  return value === null || value.trim().toLowerCase() === "secret";
}

/** Whether the app a copy came from is one the history leaves out (app ids and program names, any case). */
export function isLeftOut(app: { appId: string; program?: string | null }, list: readonly string[]): boolean {
  const names = new Set(list.map((name) => name.toLowerCase()));
  const candidates = [app.appId, app.program ?? ""].map((name) => name.toLowerCase()).filter(Boolean);
  return candidates.some((name) => names.has(name));
}

/** What a copy is, by the type that will be read. */
export type CopyKind = { kind: "image"; mime: string } | { kind: "files"; mime: string } | { kind: "text"; mime: string };

const IMAGE_TYPES = ["image/png", "image/jpeg", "image/webp", "image/gif", "image/bmp"];
const TEXT_TYPES = ["text/plain;charset=utf-8", "text/plain;charset=UTF-8", "UTF8_STRING", "text/plain", "TEXT", "STRING"];

/**
 * The type to read: an image (PNG first), else files (a URI list, as Files
 * and browsers put them), else text. Null for a copy with none of these
 * (an app's own type alone): nothing is kept.
 */
export function chooseType(mimeTypes: readonly string[]): CopyKind | null {
  const has = new Set(mimeTypes);
  const image = IMAGE_TYPES.find((type) => has.has(type));
  if (image) return { kind: "image", mime: image };
  if (has.has("text/uri-list")) return { kind: "files", mime: "text/uri-list" };
  if (has.has("x-special/gnome-copied-files")) return { kind: "files", mime: "x-special/gnome-copied-files" };
  const text = TEXT_TYPES.find((type) => has.has(type)) ?? mimeTypes.find((type) => type.startsWith("text/plain"));
  return text ? { kind: "text", mime: text } : null;
}

/** Why a copy was not kept, as the row counts them. */
export type SkipReason = "secret" | "password field" | "left out" | "paused";

/** The facts about one copy, found out before anything is read. */
export interface CopyFacts {
  mimeTypes: readonly string[];
  /** The app that had the keyboard, if a window did. */
  app: { appId: string; program?: string | null } | null;
  /** Dashi's vault was showing (Settings › Passwords). */
  vault: boolean;
  /** AT-SPI says the focused field is a password field. */
  passwordField: boolean;
  /** The screen is being shared or recorded, or is locked. */
  paused: boolean;
}

/** Keep it (and as what), or why not; the hint's value is checked after this says "read the hint". */
export type Verdict = { keep: CopyKind; readHint: boolean } | { skip: SkipReason } | { ignore: true };

export function verdict(facts: CopyFacts, leftOut: readonly string[]): Verdict {
  if (facts.paused) return { skip: "paused" };
  if (concealedByType(facts.mimeTypes)) return { skip: "secret" };
  if (facts.vault) return { skip: "secret" };
  if (facts.app && isLeftOut(facts.app, leftOut)) return { skip: "left out" };
  if (facts.passwordField) return { skip: "password field" };
  const kind = chooseType(facts.mimeTypes);
  if (!kind) return { ignore: true };
  return { keep: kind, readHint: hasPasswordHint(facts.mimeTypes) };
}
